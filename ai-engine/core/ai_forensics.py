"""
AI Writing Forensics Engine (ULTRA Tier)
Evaluates statistical perplexity, burstiness, and sentence-level structural rhythm
to estimate the probability that a document was generated by an LLM (ChatGPT/Gemini/Claude).
"""

import math
import re
from typing import Dict, List, Tuple


def split_sentences(text: str) -> List[str]:
    """Splits text into meaningful sentences while ignoring abbreviations."""
    raw_sentences = re.split(r"(?<=[.!?])\s+", text)
    return [s.strip() for s in raw_sentences if len(s.strip()) > 10]


def calculate_burstiness(sentence_lengths: List[int]) -> Tuple[float, float]:
    """
    Burstiness is the standard deviation of sentence lengths.
    Human writing has high burstiness (varied rhythm).
    AI writing has low burstiness (flat, uniform sentence lengths).
    """
    if not sentence_lengths:
        return 0.0, 0.0

    mean_len = sum(sentence_lengths) / len(sentence_lengths)
    variance = sum((l - mean_len) ** 2 for l in sentence_lengths) / len(
        sentence_lengths
    )
    std_dev = math.sqrt(variance)

    # Coefficient of Variation (CV = std_dev / mean)
    cv = (std_dev / mean_len) if mean_len > 0 else 0.0
    return round(std_dev, 2), round(cv, 2)


def calculate_lexical_diversity(tokens: List[str]) -> float:
    """Type-Token Ratio (TTR): measures vocabulary richness."""
    if not tokens:
        return 0.0
    unique_tokens = set(t.lower() for t in tokens)
    return round(len(unique_tokens) / len(tokens), 3)


def estimate_perplexity_proxy(text: str) -> float:
    """
    Character and word transition entropy proxy.
    Calculates statistical surprise based on character n-gram distribution.
    Lower entropy/perplexity = smoother, more predictable text (AI signature).
    """
    clean = re.sub(r"\s+", " ", text.lower()).strip()
    if len(clean) < 50:
        return 50.0

    # Trigram frequencies
    trigrams = [clean[i : i + 3] for i in range(len(clean) - 2)]
    freq = {}
    for tg in trigrams:
        freq[tg] = freq.get(tg, 0) + 1

    total = len(trigrams)
    entropy = -sum(
        (count / total) * math.log2(count / total) for count in freq.values()
    )

    # Scale entropy to a 0-100 perplexity index
    perplexity_index = min(100.0, max(0.0, entropy * 12.0))
    return round(perplexity_index, 2)


def analyze_ai_writing(text: str) -> Dict:
    """
    Performs forensic analysis on document text and outputs:
    1. Overall AI probability score (0-100%)
    2. Perplexity and burstiness metrics
    3. Sentence-by-sentence classification for visual heatmap rendering
    """
    sentences = split_sentences(text)
    if len(sentences) < 3:
        return {
            "ai_probability": 0.0,
            "verdict": "INSUFFICIENT_TEXT",
            "message": "Text is too short for reliable statistical AI forensics (minimum 3 sentences required).",
            "sentence_analysis": [],
        }

    sentence_lengths = [len(s.split()) for s in sentences]
    std_dev, cv = calculate_burstiness(sentence_lengths)
    perplexity = estimate_perplexity_proxy(text)
    words = re.findall(r"\b\w+\b", text.lower())
    ttr = calculate_lexical_diversity(words)

    # Scoring heuristic based on empirical LLM vs Human markers:
    # 1. Burstiness penalty: if CV < 0.35, high AI indicator (+35%)
    # 2. Perplexity penalty: if perplexity < 65, smooth AI indicator (+35%)
    # 3. Uniform sentence penalty: if mean sentence is between 15-22 words and low std dev (+20%)
    ai_score = 0.0

    if cv < 0.25:
        ai_score += 45.0
    elif cv < 0.38:
        ai_score += 30.0
    elif cv < 0.50:
        ai_score += 15.0

    if perplexity < 60.0:
        ai_score += 40.0
    elif perplexity < 70.0:
        ai_score += 25.0
    elif perplexity < 80.0:
        ai_score += 10.0

    mean_len = sum(sentence_lengths) / len(sentence_lengths)
    if 14 <= mean_len <= 23 and std_dev < 4.5:
        ai_score += 15.0

    ai_probability = min(98.0, max(2.0, round(ai_score, 1)))

    if ai_probability >= 70.0:
        verdict = "HIGHLY_LIKELY_AI"
    elif ai_probability >= 40.0:
        verdict = "SUSPECTED_MIXED_OR_PARAPHRASED"
    else:
        verdict = "LIKELY_HUMAN"

    # Analyze individual sentences for heatmap
    sentence_records = []
    char_offset = 0
    for idx, s in enumerate(sentences):
        s_len = len(s.split())
        # Deviation from document mean
        dev = abs(s_len - mean_len)
        s_prob = ai_probability
        if dev > 8:
            s_prob = max(5.0, s_prob - 25.0)  # High burstiness sentence = likely human
        elif dev < 2:
            s_prob = min(95.0, s_prob + 10.0)  # Clustered near mean = likely AI

        start_char = text.find(s, char_offset)
        if start_char == -1:
            start_char = char_offset
        end_char = start_char + len(s)
        char_offset = end_char

        sentence_records.append(
            {
                "index": idx,
                "sentence": s,
                "word_count": s_len,
                "ai_probability": round(s_prob, 1),
                "start_char": start_char,
                "end_char": end_char,
                "classification": "AI"
                if s_prob >= 60
                else ("MIXED" if s_prob >= 35 else "HUMAN"),
            }
        )

    return {
        "ai_probability": ai_probability,
        "verdict": verdict,
        "metrics": {
            "burstiness_std_dev": std_dev,
            "coefficient_of_variation": cv,
            "perplexity_index": perplexity,
            "lexical_diversity_ttr": ttr,
            "average_sentence_length": round(mean_len, 1),
            "total_sentences": len(sentences),
            "total_words": len(words),
        },
        "sentence_analysis": sentence_records,
    }
